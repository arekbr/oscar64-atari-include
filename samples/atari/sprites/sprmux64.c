int main(void)
{
	SpriteVideoState saved;
	if (!start_sprites(&saved))
		return 1;
	byte phase = 0;
	while (!(cons_keys() & CONSOL_START))
	{
		start_frame();
		for (byte row = 0; row < 8; ++row)
		{
			byte angle = phase + 11 * row;
			int step = costab[angle];
			int x = 172 - (step >> 1) - 3 * step;
			if (angle & 0x80)
			{
				x += 7 * step;
				step = -step;
			}
			for (byte i = 0; i < 8; ++i)
			{
				draw_sprite(x, 52 + 25 * row, angle & 0x80 ? 7 - i : i);
				x += step;
			}
		}
		abm_screen_present(&display);
		phase += 5;
	}
	stop_sprites(&saved);
	return 0;
}
